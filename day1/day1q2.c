//WAP to calculate sum,product,difference and quotient of two nos:
 
#include<stdio.h>
int main()
{
 int a,b;
 printf("Enter two nos");
 scanf("%d%d",&a,&b);
 printf("Sum is:- %d \n",a+b);
 printf("Difference is:- %d \n",a-b);
 printf("Product is:- %d \n",a*b);
 printf("Quotient is:- %d \n",a/b);
 return 0;
}
